HDR = ["信息板块", "具体字段名称", "填报说明", "官方 Help", "重要提醒", "覆盖范围"]

X = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"


def esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def build(path):
    strs, idx = [], {}

    def si(v):
        if v not in idx:
            idx[v] = len(strs)
            strs.append(v)
        return idx[v]

    rows_xml = []
    for i, r in enumerate([HDR] + [list(x) for x in ROWS], 1):
        cs = "".join('<c r="%s%d" t="s"><v>%d</v></c>' % (chr(64 + j), i, si(v))
                     for j, v in enumerate(r, 1))
        rows_xml.append('<row r="%d">%s</row>' % (i, cs))
    sheet = ('<?xml version="1.0"?><worksheet xmlns="%s"><sheetData>%s</sheetData></worksheet>'
             % (X, "".join(rows_xml)))
    ss = ('<?xml version="1.0"?><sst xmlns="%s">%s</sst>'
          % (X, "".join('<si><t xml:space="preserve">%s</t></si>' % esc(s) for s in strs)))
    wb = ('<?xml version="1.0"?><workbook xmlns="%s"><sheets>'
          '<sheet name="日本签证申请表字段" sheetId="1"/></sheets></workbook>' % X)
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("[Content_Types].xml",
                   '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/'
                   'package/2006/content-types"/>')
        z.writestr("xl/workbook.xml", wb)
        z.writestr("xl/sharedStrings.xml", ss)
        z.writestr("xl/worksheets/sheet1.xml", sheet)
    return path


